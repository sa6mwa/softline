/* Shared scalar cell widths for local cursor accounting and prompt layout.
 * No producer bytes or terminal reflow history are retained here. */
/* Sorted scalar intervals from Python's Unicode 16.0.0 database.
 * This classifies scalars only; it does not retain or shape producer text. */
static int sl_codepoint_in_ranges(unsigned long cp,
                                  const unsigned long ranges[][2], size_t end) {
  size_t first = 0;
  while (first < end) {
    size_t middle = first + (end - first) / 2;
    if (cp < ranges[middle][0])
      end = middle;
    else if (cp > ranges[middle][1])
      first = middle + 1;
    else
      return 1;
  }
  return 0;
}

